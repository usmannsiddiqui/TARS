#!/bin/sh
# Writes apps/ios/Config.xcconfig (git-ignored) from an .env file: CONVEX_URL, AUTH0_DOMAIN, AUTH0_CLIENT_ID only.
# Usage: apps/ios/scripts/make-config.sh [path/to/.env.local] [apple-team-id]
# Values are never printed.
set -eu
here=$(cd "$(dirname "$0")/.." && pwd)
env_file=${1:-"$here/../../.env.local"}
team=${2:-}
[ -f "$env_file" ] || { echo "No env file at $env_file" >&2; exit 1; }

value() {
  # Last assignment wins, like dotenv; strips surrounding quotes.
  grep -E "^$1=" "$env_file" | tail -n 1 | cut -d= -f2- | sed -e 's/^["'\'']//' -e 's/["'\'']$//'
}

out="$here/Config.xcconfig"
{
  echo "// Generated by scripts/make-config.sh. Git-ignored: do not commit."
  for name in CONVEX_URL AUTH0_DOMAIN AUTH0_CLIENT_ID; do
    v=$(value "$name")
    [ -n "$v" ] || { echo "$name is missing from $env_file" >&2; exit 1; }
    # xcconfig reads "//" as a comment, so the URL's slashes are split with an empty $().
    printf '%s = %s\n' "$name" "$(printf '%s' "$v" | sed 's#//#/$()/#g')"
  done
  echo "DEVELOPMENT_TEAM = $team"
} > "$out.tmp"
mv "$out.tmp" "$out"
echo "Wrote $out"
